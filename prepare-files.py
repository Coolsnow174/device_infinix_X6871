"""Regenerate the hardware blob inventory from an unpacked stock dump."""
import argparse
import collections
import json
import os
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument('dump', type=Path)
a = p.parse_args()
here = Path(__file__).resolve().parent
entries = {}; links = []
for part in ('vendor', 'odm'):
    root = a.dump / part
    for base, dirs, files in os.walk(root, followlinks=False):
        dirs[:] = sorted(d for d in dirs if not (Path(base) / d).is_symlink())
        for name in sorted(files):
            f = Path(base) / name
            rel = f.relative_to(a.dump).as_posix()
            sub = f.relative_to(root).as_posix()
            if sub == 'build.prop' or sub.startswith(('etc/selinux/', 'lib/modules/', 'lib64/modules/')):
                continue
            if sub in ('etc/fstab.mt6895', 'etc/vintf/manifest.xml', 'etc/vintf/compatibility_matrix.xml'):
                continue
            if f.is_symlink():
                target = os.readlink(f)
                resolved = os.path.normpath(os.path.join(os.path.dirname(rel), target)) if not target.startswith('/') else target.lstrip('/')
                links.append((rel, resolved)); continue
            if f.is_file(): entries[rel] = ';MAKE_COPY_RULE_ONLY' if sub.startswith('overlay/') else ''
# Map stock symlinks to extract-utils install_symlink rules, never host-absolute links.
for rel, target in links:
    if target in entries:
        entries[target] += (';SYMLINK=' + rel)
# Prefix every ELF module: retain its installed filename, avoid collisions with
# AOSP and libraries installed in several hardware/architecture subdirectories.
for rel in entries:
    f = a.dump / rel
    with f.open('rb') as stream: magic = stream.read(4)
    if f.name in ('ISP_mapping.db', 'ISP_param.db'):
        entries[rel] += ';MAKE_COPY_RULE_ONLY'
    if magic == b'\x7fELF':
        entries[rel] += ';MODULE=x6871_' + rel.replace('/lib64/', '/lib/').replace('/', '_').removesuffix('.so')
# ELF dependencies are mapped to the selected stock modules by architecture below
# through lib_fixups in extract-files.py; no binary patching is inherited.
(here / 'proprietary-files.txt').write_text('# Stock XOS16 vendor and ODM hardware inventory; generated by prepare-files.py\n' + '\n'.join(rel + entries[rel] for rel in sorted(entries)) + '\n')
(here / 'stock-symlinks.json').write_text(json.dumps(links, indent=2) + '\n')
print(f'{len(entries)} files; {len(links)} stock symlinks')
